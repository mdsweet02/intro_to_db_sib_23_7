-- 1. Список оправ, которые были реализованы «I-го» числа
SELECT DISTINCT o.АртикулОправы, o.Наименование, o.Цена
FROM dbo.Оправы o
JOIN dbo.Заказ_Оправы zo ON o.АртикулОправы = zo.АртикулОправы
JOIN dbo.Заказ z ON zo.НомерЗаказа = z.НомерЗаказа
WHERE z.ДатаОформления = '2025-12-04';

-- 2. Перечень заказов, где ФИО заказчика = 'Иванов Иван Иванович'
SELECT *
FROM dbo.Заказ
WHERE ФИОЗаказчика = 'Иванов Иван Иванович';

-- 3. Количество заказов, выполненных каждым из работников
SELECT r.ФИО, COUNT(zu.НомерЗаказа) AS КоличествоЗаказов
FROM dbo.Работники r
LEFT JOIN dbo.Заказ_Услуги zu ON r.ТабельныйНомер = zu.КодРаботника
GROUP BY r.ФИО;

-- 4. Вычислить плановую дату выполнения каждого из заказов
SELECT 
    z.НомерЗаказа,
    z.ФИОЗаказчика,
    z.ДатаОформления,
    z.СрокИзготовления,
    DATEADD(DAY, 
        CAST(LEFT(z.СрокИзготовления, CHARINDEX(' ', z.СрокИзготовления)-1) AS INT), 
        z.ДатаОформления) AS ПлановаяДатаВыполнения
FROM dbo.Заказ z;

-- 5. Сумма прихода по каждому из дней I-го месяца текущего года
SELECT 
    CAST(kz.Дата AS DATE) AS Дата,
    SUM(kz.Сумма) AS СуммаПрихода
FROM dbo.Касса_Заказ kz
WHERE MONTH(kz.Дата) = 12 AND YEAR(kz.Дата) = YEAR(GETDATE())
GROUP BY CAST(kz.Дата AS DATE)
ORDER BY Дата;
